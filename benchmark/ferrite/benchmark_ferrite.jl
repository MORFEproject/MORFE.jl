"""
Ferrite-path benchmark for MORFE.jl.

Equivalent to legacy_morfe/MORFE2.0/launch_benchmark.jl, using the new API
with Ferrite.jl as the FEM backend.

Measured phases (analogues in brackets):
  §1  Spectrum           [eigs inside dpim]
  §2  Cohomological solve    [full dpim loop, quad + cubic together]
  §3  Realification          [realification!]

count_terms_dyn equivalent is trivial (length(mset)) — not timed.
store_dyn_and_map has no equivalent; W and R already hold all data.

Mesh: beam_h27.msh — pure H27 quadratic Lagrange hex, generated by
	  generate_beam_mesh.jl (1000 × 10 × 24 mm, 40 × 2 × 2 elements).
	  Run generate_beam_mesh.jl once before this script.
	  Expected free DoFs: 5925 (≈ MORFE2.0's 5952).
ROM:  2 modes, max_degree = 11, N_EXT = 0.
FEM:  O5 Re/Im decomposition in ferrite_assembly.jl (no heap allocs in accumulate_qp!).
"""

using Pkg: Pkg
Pkg.activate(@__DIR__)
if !haskey(Pkg.project().dependencies, "MORFE")
	Pkg.develop(Pkg.PackageSpec(path = joinpath(@__DIR__, "../..")))
	Pkg.add(["Ferrite", "FerriteGmsh", "Arpack", "LinearMaps", "StaticArrays",
		"BenchmarkTools", "Gmsh"])
end
Pkg.instantiate()

using MORFE
using Ferrite
using FerriteGmsh
using SparseArrays
using LinearAlgebra
using Arpack
using LinearMaps
using StaticArrays
using Printf

include(joinpath(@__DIR__, "../Ferrite/ferrite_assembly.jl"))

# -----------------------------------------------------------------------
# 1. Mesh and FE setup
# -----------------------------------------------------------------------

const _msh = joinpath(@__DIR__, "beam_h27.msh")
isfile(_msh) || error("Mesh not found: run generate_beam_mesh.jl first.")

println("Loading mesh …")
grid = togrid(_msh)   # "Dirichlet" physical group already in .msh

ip     = Lagrange{RefHexahedron, 2}()^3   # 27-node quadratic Lagrange, matches H27
geo_ip = Lagrange{RefHexahedron, 2}()     # quadratic geometry (isoparametric H27)
qr     = QuadratureRule{RefHexahedron}(3) # 27 QPs (integrates degree 5)
cv     = CellValues(qr, ip, geo_ip)

dh = DofHandler(grid)
add!(dh, :u, ip)
close!(dh)

ch = ConstraintHandler(dh)
add!(ch, Dirichlet(:u, getfacetset(grid, "Dirichlet"), (x, t) -> zeros(3), [1, 2, 3]))
close!(ch)
update!(ch, 0.0)

println("Total DOFs : ", ndofs(dh))

# -----------------------------------------------------------------------
# 2. Linear matrices
# -----------------------------------------------------------------------

E = 160e3
ν = 0.22
ρ = 2.32e-3
λ_lame = (E * ν) / ((1 + ν) * (1 - 2ν))
μ_lame = E / (2(1 + ν))
α = 0.5369754008568333/500.0
β = 0.0

K_full = allocate_matrix(dh)
M_full = allocate_matrix(dh)
assemble_KM!(K_full, M_full, dh, cv, λ_lame, μ_lame, ρ)

free          = sort(setdiff(1:ndofs(dh), ch.prescribed_dofs))
free_to_local = Dict(d => i for (i, d) in enumerate(free))
n_free        = length(free)

K = K_full[free, free]
M = M_full[free, free]
C = α * M + β * K

println("Free DOFs  : ", n_free)

# -----------------------------------------------------------------------
# 3. Multiindex set
# -----------------------------------------------------------------------

const ROM = 2 * 1 # one physical mode
const N_EXT = 2 * 1 # two external variables (r₁, r₂) for harmonic forcing, one "cosine term"
const NVAR = ROM + N_EXT
const max_degree = 5

mset = all_multiindices_up_to(NVAR, max_degree; min_degree = 1)
_max_uniq = length(mset)

# -----------------------------------------------------------------------
# §1 — Spectrum
# -----------------------------------------------------------------------

println("\n§1  Spectrum …")
solver_eig = StructureModalDampingEigensolver(10, α, β)

r1 = @timed spectrum(K, M, solver_eig; sorter! = (args...) -> nothing)
eigenproblem = r1.value
(eigenvalues, Y, X) = get_eigenpairs(eigenproblem)

println("  First eigenvalues:")
for (i, λi) in enumerate(eigenvalues)
	println("    mode $i: λ = $λi")
end

FOM = n_free
select_master_modes_by_sorting(eigenproblem, ROM)

master_eigenvalues = SVector{ROM, ComplexF64}(eigenvalues[1:ROM])
master_modes = Y[:, 1, 1:ROM]   # position component of right eigenvectors
left_eigenmodes = X[:, 1:ROM]   # adjoint mode shapes — X is FOM × n_eigs from get_eigenpairs

ORD_model = size(eigenproblem.eigenmodes, 2)
master_modes_derivatives = zeros(ComplexF64, FOM, ORD_model - 1, ROM)
for r in 1:ROM
	for k in 1:(ORD_model-1)
		master_modes_derivatives[:, k, r] .= Y[:, k+1, r]
	end
end

# -----------------------------------------------------------------------
# 4. Force terms  (FEMMultilinearMap, O5 Re/Im path)
# -----------------------------------------------------------------------

term_quad = FerriteGeometricNonlinearity{2}(
	dh, cv, free_to_local, n_free, λ_lame, μ_lame; max_unique_cols = _max_uniq)
term_cubic = FerriteGeometricNonlinearity{3}(
	dh, cv, free_to_local, n_free, λ_lame, μ_lame; max_unique_cols = _max_uniq)

# Forcing frequency = damped natural frequency of mode 1; force shape = mode 1
Ω_force = abs(eigenvalues[1])
f_vec = real(2.5 .* (M * master_modes[:, 1])) # alpha = 5; real: physical forcing is a real spatial vector

# Forcing matrix N×N_EXT (filled after eigenproblem; captured by closure).
# f_vec · sum(r) = f_vec · (r₁+r₂) = f_vec · 2 cos(Ωt)
term_forcing = MultilinearMap(
	(res, r) -> (res .+= f_vec * sum(r)),
	(0, 0), 1,
)
# r1' = i Ω_force r1 -> r1 = exp(im * Ω_force * t)
# r2' = -i Ω_force r2 -> r2 = exp(-im * Ω_force * t)
# 2 cos(Ωt) = exp(im * Ωt) + exp(-im * Ωt) = r1 + r2

ext_sys = ExternalSystem((im * Ω_force, -im * Ω_force))

model = NDOrderModel(
	(K, C, M),
	(term_quad, term_cubic, term_forcing),
	ext_sys,
)

resonance_set = resonance_set_from_complex_normal_form_style(
	mset, Vector{ComplexF64}(master_eigenvalues), 0.05;
	external_eigenvalues = ComplexF64[im*Ω_force, -im*Ω_force])

# -----------------------------------------------------------------------
# §2 — Cohomological solve  (quadratic + cubic, full model)
# -----------------------------------------------------------------------

println("\n§2  Cohomological solve (max_degree = $max_degree) …")
r2 = @timed solve_cohomological_problem(
	model, mset,
	master_eigenvalues,
	master_modes, left_eigenmodes,
	resonance_set;
	master_modes_derivatives = master_modes_derivatives,
	conjugate_permutation = [2, 1, 4, 3],
	# benchmark_dir = joinpath(@__DIR__, "benchmark_results"),
)
(W, R) = r2.value

println("\nReduced dynamics coefficients:")
for m in 1:length(R.poly.multiindex_set.exponents)
	mi = R.poly.multiindex_set.exponents[m]
	c = R.poly.coefficients[:, m]
	any(abs.(c) .> 1e-12) && println("$mi   $(c[1]) \t $(c[2])")
end

# -----------------------------------------------------------------------
# Summary table
# -----------------------------------------------------------------------

to_gb(b) = round(b / 1024^3; digits = 1)
sep = "=" ^ 67

println()
println(sep)
println("MORFE.jl — Ferrite Benchmark   (clamped-clamped beam, beam_h27.msh)")
@printf("  Mesh   : H27 quadratic Lagrange hex (40×2×2)    FOM = %d\n", FOM)
@printf("  ROM    : %d modes   max_degree = %d   N_EXT = %d\n", ROM, max_degree, N_EXT)
println("-" ^ 67)
@printf("  %-32s  %9s  %11s  %7s\n", "Phase", "Time (s)", "Memory (GB)", "GC (s)")
println("-" ^ 67)
@printf("  §1  %-28s  %9.3f  %11.2f  %7.3f\n",
	"Spectrum", r1.time, to_gb(r1.bytes), r1.gctime)
@printf("  §2  %-28s  %9.3f  %11.2f  %7.3f\n",
	"Cohomological solve", r2.time, to_gb(r2.bytes), r2.gctime)
println("-" ^ 67)
@printf("  %-32s  %9.3f  %11.1f  %7.3f\n",
	"Σ  Cumulative (§1+§2)", r1.time + r2.time, to_gb(r1.bytes)+to_gb(r2.bytes), r1.gctime+r2.gctime)
println("Monomials (max_degree=$max_degree) =", length(mset.exponents))
println(sep)

# --- Convergence study: sweep over forcing levels ---
ENV["GKSwstype"] = "100"  # suppress GUI window; write PNGs directly
using Random
using Plots
r_levels = [0.0, 0.02, 0.05, 0.1]
err_conv = invariance_error_convergence(model, W, R;
	n_samples = 300, r_magnitudes = r_levels, rng = MersenneTwister(0))

println("\n=== Invariance error convergence ===")
for res in err_conv
	println("  |r| = $(res.r_magnitude)  →  max_order = $(res.max_order)",
		"  s̄ = $(round(res.s_bar, digits=4))",
		"  force_err ∈ [$(round(minimum(res.force_errors), sigdigits=2)),",
		" $(round(maximum(res.force_errors), sigdigits=2))]")
end

plots = plot_invariance_convergence(err_conv)
savefig(plots.full, joinpath(@__DIR__, "invariance_convergence_full.png"))
savefig(plots.master, joinpath(@__DIR__, "invariance_convergence_master.png"))
println("\nConvergence plots saved to: ", @__DIR__)

println("\n" * "="^80)
println("Demo finished successfully.")
